SET country_id = (
SELECT c.id
FROM countries c
WHERE LOWER(c.name) = LOWER(d.country)
)
WHERE d.country IS NOT NULL
AND d.country_id IS NULL
AND EXISTS (
SELECT 1 FROM countries c
WHERE LOWER(c.name) = LOWER(d.country)
);

